/**
 * حدس‌های معتبر به‌صورت `Set` تا جست‌وجو ثابت‌زمان باشد.
 *
 * فهرست تولیدشده از قبل نرمال‌شده است، پس فقط حدسِ کاربر نرمال می‌شود. روش
 * قبلی (`words.some(w => normalize(w) === target)`) برای هر حدس ۴۰ هزار بار
 * `normalize` صدا می‌زد — روی موبایل ده‌ها میلی‌ثانیه گیر می‌انداخت.
 */
const validGuesses = new Set(words);

/** آیا این کلمه یک حدسِ معتبر است؟ */
export function isValidWord(word: string): boolean {
  return validGuesses.has(normalize(word));
}

/**
 * پازلِ یک شماره‌ی مشخص.
 *
 * اگر پازل هنوز نرسیده باشد، شماره‌اش کمتر از ۱ باشد، یا از فهرست جواب‌ها
 * بیرون بزند، خطا می‌دهد.
 */
export function getPuzzle(puzzleNumber: number, now: Date = new Date()): Puzzle {
  assertPuzzleAvailable(puzzleNumber, now);
  const solution = answers[puzzleNumber - 1];
  if (solution === undefined) {
    throw new Error(
      `فهرست کلمه‌های روز تمام شده: پازل ${puzzleNumber} خواسته شد ولی فهرست ${answers.length} کلمه دارد`,
    );
  }
  return { number: puzzleNumber, solution, date: puzzleNumberToDate(puzzleNumber) };
}

/** پازل امروز. برای همه‌ی کاربران در یک لحظه یکسان است. */
export function getDailyPuzzle(now: Date = new Date()): Puzzle {
  return getPuzzle(getCurrentPuzzleNumber(now), now);
}

/** چند روز کلمه‌ی آماده باقی مانده است. */
export function remainingRunway(now: Date = new Date()): number {
  return answers.length - getCurrentPuzzleNumber(now);
}
