export const WORD_LENGTH = 5;

/**
 * فهرست حدس‌های معتبر به‌صورت یک رشته‌ی به‌هم‌چسبیده ذخیره می‌شود و اینجا باز
 * می‌شود. آرایه‌ای از ۴۰ هزار رشته در سورس، حدود ۱۶۰ کیلوبایت گیومه و ویرگول
 * اضافه می‌کرد.
 */
function unpackWords(packed: string): string[] {
  const out: string[] = new Array<string>(wordCount);
  for (let i = 0; i < wordCount; i++) {
    out[i] = packed.slice(i * WORD_LENGTH, (i + 1) * WORD_LENGTH);
  }
  return out;
}

